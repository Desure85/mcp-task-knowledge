#!/usr/bin/env node
/**
 * DX-21: generate Homebrew formula and Scoop manifest from release assets.
 *
 * This is the generator half of the release pipeline: it takes a descriptor
 * (version, repository, per-platform URL + sha256) and writes deterministic
 * `mcp-task-knowledge.rb` / `mcp-task-knowledge.json`. Publishing/uploading is
 * intentionally outside this script.
 */
import fs from 'node:fs';
import path from 'node:path';

const SEMVER_RE = /^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/;
const SHA_RE = /^[a-f0-9]{64}$/;
const ASSET_KEYS = new Set(['darwin-arm64', 'darwin-x64', 'linux-arm64', 'linux-x64', 'win-x64']);

export function validateReleaseConfig(config) {
  const errors = [];
  if (!config || typeof config !== 'object') return ['config is not an object'];
  if (!SEMVER_RE.test(config.version ?? '')) errors.push('version must be semver');
  if (typeof config.repository !== 'string' || !/^https:\/\/github\.com\/[^/]+\/[^/]+$/.test(config.repository)) {
    errors.push('repository must be https://github.com/owner/repo');
  }
  if (typeof config.description !== 'string' || !config.description.trim()) errors.push('description is required');
  if (typeof config.license !== 'string' || !config.license.trim()) errors.push('license is required');

  const assets = config.assets;
  if (!assets || typeof assets !== 'object') {
    errors.push('assets is required');
    return errors;
  }
  for (const [key, asset] of Object.entries(assets)) {
    if (!ASSET_KEYS.has(key)) errors.push(`unknown asset key '${key}'`);
    if (!asset || typeof asset !== 'object') { errors.push(`asset '${key}' is not an object`); continue; }
    if (typeof asset.url !== 'string' || !asset.url.startsWith('https://')) errors.push(`asset '${key}' url must be https`);
    if (!SHA_RE.test(asset.sha256 ?? '')) errors.push(`asset '${key}' sha256 must be 64 lowercase hex`);
  }
  const hasDarwin = ['darwin-arm64', 'darwin-x64'].some((key) => assets[key]);
  const hasLinux = ['linux-arm64', 'linux-x64'].some((key) => assets[key]);
  if (!hasDarwin && !hasLinux) errors.push('at least one macOS/Linux asset is required for Homebrew');
  if (hasDarwin && (!assets['darwin-arm64'] || !assets['darwin-x64'])) errors.push('darwin-arm64 and darwin-x64 must be provided together');
  if (hasLinux && (!assets['linux-arm64'] || !assets['linux-x64'])) errors.push('linux-arm64 and linux-x64 must be provided together');
  if (!assets['win-x64']) errors.push('win-x64 asset is required for Scoop');
  return errors;
}

export function generateHomebrewFormula(config) {
  const assets = config.assets;
  const mac = [
    assets['darwin-arm64'] ? `    if Hardware::CPU.arm?\n      url "${assets['darwin-arm64'].url}"\n      sha256 "${assets['darwin-arm64'].sha256}"\n    else\n      url "${assets['darwin-x64']?.url ?? ''}"\n      sha256 "${assets['darwin-x64']?.sha256 ?? ''}"\n    end` : '',
  ].filter(Boolean).join('\n');
  const linux = [
    assets['linux-arm64'] ? `    if Hardware::CPU.arm?\n      url "${assets['linux-arm64'].url}"\n      sha256 "${assets['linux-arm64'].sha256}"\n    else\n      url "${assets['linux-x64']?.url ?? ''}"\n      sha256 "${assets['linux-x64']?.sha256 ?? ''}"\n    end` : '',
  ].filter(Boolean).join('\n');

  return `# Generated by scripts/gen-package-managers.mjs — do not edit by hand.
class McpTaskKnowledge < Formula
  desc "${config.description}"
  homepage "${config.repository}"
  version "${config.version}"
  license "${config.license}"

${mac ? `  on_macos do\n${mac}\n  end\n\n` : ''}${linux ? `  on_linux do\n${linux}\n  end\n\n` : ''}  def install
    bin.install Dir["mcp-task-knowledge-*"].first => "mcp-task-knowledge"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/mcp-task-knowledge --version")
  end
end
`;
}

export function generateScoopManifest(config) {
  const win = config.assets['win-x64'];
  return `${JSON.stringify({
    $schema: 'https://raw.githubusercontent.com/ScoopInstaller/Scoop/master/schema.json',
    version: config.version,
    description: config.description,
    homepage: config.repository,
    license: config.license,
    architecture: {
      '64bit': { url: win.url, hash: `sha256:${win.sha256}` },
    },
    bin: [['mcp-task-knowledge.exe', 'mcp-task-knowledge']],
  }, null, 2)}\n`;
}

function main() {
  const args = process.argv.slice(2);
  const get = (name, fallback) => {
    const index = args.indexOf(`--${name}`);
    return index >= 0 && args[index + 1] ? args[index + 1] : fallback;
  };
  const configPath = get('config', 'release-assets.json');
  const outDir = get('out', 'dist-packages');
  const config = JSON.parse(fs.readFileSync(configPath, 'utf8'));
  const errors = validateReleaseConfig(config);
  if (errors.length) {
    console.error('release config invalid:');
    for (const error of errors) console.error(`  - ${error}`);
    process.exit(1);
  }
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, 'mcp-task-knowledge.rb'), generateHomebrewFormula(config), 'utf8');
  fs.writeFileSync(path.join(outDir, 'mcp-task-knowledge.json'), generateScoopManifest(config), 'utf8');
  console.log(`package manifests written to ${outDir}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.url.replace('file:///', ''))) {
  main();
}
