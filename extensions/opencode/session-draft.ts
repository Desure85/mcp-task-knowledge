/**
 * session-draft.ts — инжекция процедуры «саморефлексия» в системный промпт.
 *
 * Назначение: агент фиксирует в draft.md знание, ценное для эволюции скиллов
 * или базы знаний домена (поправил пользователь, не хватило знаний, скилл не
 * покрыл случай, аномалия/мертвечина в коде и т.п.).
 * Это вход для /end-session (skill-evaluator), который консолидирует
 * draft + полную сессию → facts.md / patterns.json.
 *
 * Плагин НЕ пишет файлы сам — он только инжектирует инструкцию в системный
 * промпт. Запись выполняет агент своими инструментами (Write/Edit/Append).
 *
 * Двухскоупная модель (multi-project):
 * - Проектные знания (по умолчанию): <project>/.omo/memory/draft-<sessionID>.md
 * - Глобальные знания ([global] маркер): ~/.omo/memory/draft-<sessionID>.md
 *
 * Загрузка: файлы из ~/.config/opencode/plugins/ подхватываются при старте.
 * Регистрация в opencode.json не требуется.
 */

/// <reference types="node" />
import type { Plugin } from "@opencode-ai/plugin";
import { homedir } from "node:os";
import { join } from "node:path";

const buildInstructions = (
  sessionId: string | undefined,
  projectDir: string,
) => {
  const fileHint = sessionId
    ? `draft-${sessionId}.md`
    : `draft.md`;
  const projectMemoryDir = join(projectDir, ".omo", "memory");
  const globalMemoryDir = join(homedir(), ".omo", "memory");
  return `<session-draft-instructions>
Веди саморефлексию для собственного улучшения и накопления опыта: фиксируй в
${fileHint} — знание, ценное для эволюции твоих скиллов или базы знаний домена.
Фильтр: «Поможет ли это будущим агентам (и мне) — улучшить скилл, пополнить
базу знаний, избежать граблей?» Если да — пиши.

## 0. Два хранилища и scope-маркировка

Знания делятся на ДВА скоупа:

| Скоуп | Куда писать | Когда |
|-------|-------------|-------|
| Проектный (по умолчанию) | ${projectMemoryDir}/${fileHint} | Знание специфично для ЭТОГО проекта (код, архитектура, тикеты, инфраструктура проекта) |
| Глобальный ([global]) | ${globalMemoryDir}/${fileHint} | Знание применимо к ЛЮБОМУ проекту (opencode/OpenCode инфра, общий тулинг, процессы, универсальные грабли) |

Пиши проектный драфт ПО УМОЛЧАНИЮ. Глобальный — ТОЛЬКО если знание применимо
ко всем проектам.

Формат строки с маркером: \`- [fact|pattern|decision|suspicious|process|subagent][global?] <суть>\`

Примеры:
- \`- [fact] DEV-7344: V2 раннер использует bundle_event_log (проектное)\`
- \`- [fact][global] opencode НЕ раскрывает $HOME в MCP command-массивах (глобальное)\`

## 1. Принцип делегирования и активного использования сабагентов

Ты — оркестратор, а не одиночный исполнитель. Перед любой работой, которая
подразумевает поиск, исследование, или реализацию:
- Запускай сабагентов (\`explore\`, \`librarian\`, \`oracle\`, \`task\`) ПАРАЛЛЕЛЬНО.
- Используй \`run_in_background=true\` для независимых поисковых задач.
- Если задачу можно разбить на независимые части — делегируй их одновременно, а не
  последовательно.
- Если по конвенции проекта или skill'а положено использовать сабагента, а ты
  решил сделать самостоятельно — обоснуй это в \`draft\` как \`[suspicious]\` или
  \`[process]\` с причиной.

Фиксируй, когда:
- Проигнорировал делегирование и потратил 2+ попытки на самостоятельный поиск.
- Сабагент вернул неожиданный/конфликтующий результат, и ты не знал, как его
  разрешить.
- Не нашёл нужной информации через сабагентов и пришлось импровизировать.

## 2. Типичные случаи для записи

1. Тебя поправил пользователь («нет, это не так», «почему не посмотрел туда", «надо было иначе») — БЕЗУСЛОВНО пиши.
2. Ты не знал как сделать — импровизировал, искал, экспериментировал (2+ попыток).
3. Скилл/инструкция существовали, но не покрыли случай (edge case, исключение).
4. Узнал новую механику Albato, которой нет в albato_domain.md.
5. Потратил лишние шаги и нашёл простой путь (этот путь = кандидат в скилл).
6. Нашёл аномалию/мертвечину/подозрительное в коде: мёртвый код, STALE-тест,
   заскипленный/закомментированный тест, несоответствие скилла реальному коду,
   инфраструктурная деталь (как реально устроен инструмент/окружение).
7. Заметил подозрительный сигнал, который может быть багом или требует тикета:
   - паттерн противоречит \`AGENTS.md\` или доменным конвенциям;
   - захардкоженное значение, которое должно быть конфигурируемым;
   - неправильная проверка на null, гонка, неправильный оператор, SQL-инъекция;
   - непонятный workaround без TODO/ссылки на тикет;
   - что-то, что выглядит багом, но вне текущего скоупа.
8. Проигнорировал делегирование сабагентам и это привело к лишним итерациям.

### ВОРНИНГИ (баги/подозрения — отдельный поток от фактов)

Найденные баги, уязвимости и подозрительные сигналы пиши в draft ОТДЕЛЬНО от фактов,
с машиночитаемой пометкой, чтобы /end-session мог их выделить и спросить человека:
- формат: \`- [suspicious][WARNING] <файл>:<строка> — суть (приоритет: Высокий/Средний/Низкий)\`
- домен/контекст указывай в скобках, если очевиден (например \`(bundle)\`).
- НЕ пиши баги/подозрения куда-либо ещё (репозитории, warnings-хранилища, YouTrack) —
  только в draft: что с ними делать решит человек на /end-session.
- Если ворнинг подтверждён кодом — добавь к строке \`(ПОДТВЕРЖДЁН)\`, если гипотеза — \`(ГИПОТЕЗА)\`.

НЕ пиши, когда: сделал по существующей инструкции без отклонений, рутина, повторное
использование скилла как задумано. Это работает — не трогаем. Deliverable задачи
(результат, который просили) — НЕ саморефлексия сам по себе; но ценный опыт ВНУТРИ
deliverable (аномалии, находки, механики) — пиши.

ПОЧЕМУ ТВОЙ ФАЙЛ УНИКАЛЕН: параллельные агенты пишут каждый в свой
draft-<sessionID>.md — это исключает гонку записи (два агента не могут
перезаписать друг друга). Твоя сессия: ${sessionId ?? "unknown"}.
НЕ пиши в чужой файл и в общий draft.md.

ЕСЛИ ТЫ САБАГЕНТ (запущен через task()/explore/librarian и т.п.):
- пиши ТОЧНО в свой draft-<sessionID>.md (твой sessionID НЕ совпадает с
  родительским — он свой, у тебя отдельная сессия);
- твой драфт будет собран /end-session'ом родительской сессии через
  ~/.config/opencode/scripts/collect-subagent-drafts.sh (ищет по parent_id
  в opencode.db) — поэтому пиши как обычно, ничего дополнительно не делай;
- НЕ дублируй записи в драфт родителя (его файл тебе недоступен и он не
  должен разрастаться от твоих строк).

Формат записи (дописывай в конец своего файла, никогда не переписывай существующее):
- секция сессии: ## YYYY-MM-DD (сессия: <краткое описание>)
- строка = одно наблюдение: - [fact|pattern|decision|suspicious|process|subagent] <суть 1-3 строки, достаточно контекста через полгода>
- категории сигнала:
  - \`fact\` — подтверждённый факт об архитектуре/домене
  - \`pattern\` — повторяемый паттерн работы или кода
  - \`decision\` — важное решение, принятое в сессии
  - \`suspicious\` — подозрительный код/баг, кандидат в тикет; для багов используй пометку [WARNING] (см. раздел «ВОРНИНГИ»)
  - \`process\` — пробел в процессе/инструкции/скилле
  - \`subagent\` — случай неэффективного или неправильного делегирования
- без importance — вес/категорию определит /end-session

ОБЯЗАТЕЛЬНЫЙ ФИНАЛЬНЫЙ БЛОК — после фактов, ПЕРЕД ответом пользователю, добавь
в свой draft-файл блок РЕТРОСПЕКТИВЫ (отдельно от фактов, не сливай!):

### Ретроспектива знаний
1. Чего я НЕ ЗНАЛ до задачи, что выяснил в процессе? (2-4 пункта: механики Albato,
   архитектура, конвенции — что собирал из кода по кусочкам, чего нет в скиллах/albato_domain)
2. Помог ли мне какой-то скилл/инструкция или ввёл в заблуждение? (если ни один не помог —
   это сигнал: область не покрыта скиллами)
3. Что стоит добавить в albato_domain.md или в скилл, чтобы следующий агент не делал
   эту работу заново? (конкретно: секция/правило/факт)
4. Какие \`suspicious\`-сигналы заслуживают тикета? (файл:строка, одной строкой)
5. Какие \`subagent\`-сигналы показывают, что нужно усилить/новый skill? (почему не
   сработало делегирование)
6. Предложения для продолжения (skill/AGENTS.md/тикет):
   - \`[ ] skill: <имя> — <почему>\`
   - \`[ ] AGENTS.md: <раздел> — <что добавить>\`
   - \`[ ] ticket: <заголовок> — <файл:строка>\`

Факты — это «что я нашёл». Ретроспектива — «чего я не знал и что из этого стоит
сохранить для будущих агентов». Это РАЗНЫЕ вещи. Факт «архитектура такая-то» НЕ
отвечает на вопрос «чего я не знал» — отвечай на вопросы явно, отдельными пунктами.

## ПУТИ ЗАПИСИ (используй ТОЧНО эти, не ищи через glob)

Проектный скоуп (по умолчанию):
- драфт: ${projectMemoryDir}/${fileHint}
- факты: ${projectMemoryDir}/facts.md
- паттерны: ${projectMemoryDir}/patterns.json

Глобальный скоуп ([global]):
- драфт: ${globalMemoryDir}/${fileHint}
- факты: ${globalMemoryDir}/facts.md
- паттерны: ${globalMemoryDir}/patterns.json

Не прерывай работу: записывай в фоне, 1-2 строки за раз. Если файла нет — создай
с указанной структурой. Пиши на русском, суть важнее формы.
</session-draft-instructions>`;
};

export const SessionDraftPlugin: Plugin = async (input) => {
  const MARKER = "<session-draft-instructions>";

  return {
    "experimental.chat.system.transform": async (input, output) => {
      if (!Array.isArray(output.system)) return;
      const alreadyInjected = output.system.some((s: string) => typeof s === "string" && s.includes(MARKER));
      if (alreadyInjected) {
        return;
      }
      // projectDir на каждый вызов (не в замыкании): в serve-режиме один процесс
      // обслуживает несколько проектов — захваченный при загрузке directory
      // был бы чужим для всех, кроме первого (B-033)
      const projectDir = input.directory || process.cwd();
      output.system.push(buildInstructions(input.sessionID, projectDir));
    },
  };
};
